"""Package the routed loop into js/data_loop.js so the app ships with the canonical
alignment and never needs a 25-minute in-browser solve to show the full loop."""
import os, sys, json
import numpy as np
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
HERE=os.path.dirname(os.path.abspath(__file__))
OUT=os.path.abspath(os.path.join(HERE,"..","out"))
JS=os.path.abspath(os.path.join(HERE,"..","js"))

P=np.load((lambda p: p if os.path.exists(p) else os.path.join(OUT,"loop_P.npy"))(os.path.join(OUT,"loop_P_rect.npy")))
S=json.load(open(os.path.join(OUT,"loop_summary.json")))
NL=chr(10)                                    # the editor un-escapes literal '\n'
pts="[" + ",".join(f"[{e:.1f},{n:.1f}]" for e,n in P) + "]"
seg=np.hypot(*(P[1:]-P[:-1]).T)
closure=float(np.hypot(P[0,0]-P[-1,0],P[0,1]-P[-1,1]))   # rectified loop: ~one step
body=("/* CANONICAL ROUTED LOOP - generated by build/make_data_loop.py. Do not edit. */"
      + NL + "window.LOOP_DATA={" + NL
      + f'"generated":"2026-08-05","length_km":{seg.sum()/1000:.2f},'
      + f'"closure_m":{closure:.0f},"solver":"solve_loop.py two-pass + taut-string rectification",'
      + NL + f'"legs":{json.dumps(S["legs"])},' + NL
      + '"pts":' + pts + "};" + NL)
open(os.path.join(JS,"data_loop.js"),"w",encoding="ascii").write(body)
print(f"wrote js/data_loop.js  ({os.path.getsize(os.path.join(JS,'data_loop.js'))/1e6:.2f} MB, "
      f"{len(P):,} points, {seg.sum()/1000:.1f} km)")
